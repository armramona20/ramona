"""One-shot build: voiceover -> timeline -> video frames -> music -> final mix.

Usage:  python3 build.py            (full build)
        python3 build.py --no-video (only regenerate VO/timeline/music and re-mix onto existing silent video)

Edit voiceover.json to change the script; scene lengths follow the voice length,
rounded up to the 0.5s beat grid so music hits land on every cut.
Needs: edge-tts (pip install edge-tts), ffmpeg, node + playwright, numpy.
"""
import json, math, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
VO_DIR = os.path.join(HERE, "vo")
OUT = os.path.join(HERE, "urthe-intoxicating-shirts.mp4")
SILENT = os.path.join(HERE, "build-silent.mp4")
GRID = 0.5


def run(cmd, **kw):
    print("+", " ".join(cmd) if isinstance(cmd, list) else cmd)
    subprocess.run(cmd, check=True, cwd=HERE, **kw)


def duration(path):
    out = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                                   "-of", "default=nw=1:nk=1", path])
    return float(out)


def tts(text, voice, rate, pitch, path):
    env = dict(os.environ)
    if os.path.exists("/root/.ccr/ca-bundle.crt"):
        env.setdefault("SSL_CERT_FILE", "/root/.ccr/ca-bundle.crt")
    cmd = ["edge-tts", "--voice", voice, f"--rate={rate}", f"--pitch={pitch}", "--text", text, "--write-media", path]
    proxy = env.get("HTTPS_PROXY") or env.get("https_proxy")
    if proxy:
        cmd[1:1] = ["--proxy", proxy]
    for attempt in range(4):
        r = subprocess.run(cmd, env=env, capture_output=True, text=True)
        if r.returncode == 0 and os.path.getsize(path) > 1000:
            return
        print(r.stderr[-400:])
    raise SystemExit("TTS failed for: " + text)


def main():
    cfg = json.load(open(os.path.join(HERE, "voiceover.json"), encoding="utf-8"))
    os.makedirs(VO_DIR, exist_ok=True)

    # 1) voiceover per scene + timeline
    t, scenes, vo = 0.0, {}, []
    for i, sc in enumerate(cfg["scenes"]):
        path = os.path.join(VO_DIR, sc["id"] + ".mp3")
        tts(sc["text"], cfg["voice"], cfg["rate"], cfg["pitch"], path)
        d = duration(path)
        lead = cfg["lead_in"] if i else 0.15
        need = lead + d + cfg["tail"] + (0.8 if i == len(cfg["scenes"]) - 1 else 0)
        length = math.ceil(max(sc["min"], need) / GRID) * GRID
        scenes[sc["id"]] = [round(t, 3), round(t + length, 3)]
        vo.append({"id": sc["id"], "file": path, "at": round(t + lead, 3), "dur": round(d, 3)})
        print(f"{sc['id']}: voice {d:.2f}s -> scene {length:.1f}s")
        t += length
    timeline = {"duration": t, "scenes": scenes, "vo": vo}
    json.dump(timeline, open(os.path.join(HERE, "timeline.json"), "w"), indent=1)
    with open(os.path.join(HERE, "timeline.js"), "w") as f:
        f.write("// generated by build.py - do not edit\nwindow.TIMELINE = " + json.dumps({"scenes": scenes}) + ";\n")
    print(f"total length: {t:.1f}s")

    # 2) video frames (silent)
    if "--no-video" not in sys.argv:
        run(["node", "render.js", os.path.basename(SILENT), "30"])

    # 3) music synced to cuts
    music = os.path.join(HERE, "build-music.wav")
    run([sys.executable, "music.py", music, "timeline.json"])

    # 4) mix: voice on top, music ducked under the voice
    inputs, chains = ["-i", SILENT, "-i", music], []
    for k, v in enumerate(vo):
        inputs += ["-i", v["file"]]
        ms = int(v["at"] * 1000)
        chains.append(f"[{k + 2}:a]aresample=44100,aformat=channel_layouts=stereo,adelay={ms}|{ms}[v{k}]")
    n = len(vo)
    fc = ";".join(chains) + ";" + "".join(f"[v{k}]" for k in range(n)) + \
        f"amix=inputs={n}:normalize=0,volume=1.6,apad=whole_dur={t},asplit=2[vo][sc];" \
        "[1:a]volume=0.55[mu];[mu][sc]sidechaincompress=threshold=0.03:ratio=6:attack=20:release=350[duck];" \
        "[duck][vo]amix=inputs=2:normalize=0,loudnorm=I=-14:TP=-1.5[a]"
    run(["ffmpeg", "-y", "-v", "error", *inputs, "-filter_complex", fc, "-map", "0:v", "-map", "[a]",
         "-c:v", "libx264", "-preset", "slow", "-crf", "23", "-maxrate", "8M", "-bufsize", "16M", "-pix_fmt", "yuv420p",
         "-c:a", "aac", "-b:a", "192k", "-shortest", "-movflags", "+faststart", OUT])
    os.remove(music)
    print("done ->", OUT)


if __name__ == "__main__":
    main()
